/**
 * Generates a screenshot for every project in src/data/projectData.ts and writes
 * a manifest (src/data/projectScreenshots.ts) mapping project id -> public image path.
 *
 * For each project the demo URL is captured if present, otherwise the GitHub repo page.
 *
 * Usage:
 *   npm run screenshots              # (re)generate all screenshots
 *   npm run screenshots -- --only gle-asl   # only re-shoot a single project
 *
 * Requires Node's TypeScript stripping to import projectData.ts directly.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import puppeteer from 'puppeteer';
import { projectData } from '../src/data/projectData.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(__dirname, '..');
const outputDir = join(projectRoot, 'public', 'images', 'projects');
const manifestPath = join(projectRoot, 'src', 'data', 'projectScreenshots.ts');

const VIEWPORT = { width: 1280, height: 800, deviceScaleFactor: 2 };
const SETTLE_MS = 2500;
const NAV_TIMEOUT = 30000;

const onlyIndex = process.argv.indexOf('--only');
const onlyId = onlyIndex !== -1 ? process.argv[onlyIndex + 1] : null;

const captureUrl = (project) => project.demoLink ?? `https://github.com/${project.githubProject}`;

/** Read the existing manifest so a --only run preserves other entries. */
const readExistingManifest = async () => {
  try {
    const source = await readFile(manifestPath, 'utf8');
    const entries = {};
    const re = /(?:'([^']+)'|([A-Za-z_$][\w$]*))\s*:\s*'([^']+)'/g;
    let match;
    while ((match = re.exec(source)) !== null) {
      entries[match[1] ?? match[2]] = match[3];
    }
    return entries;
  } catch {
    return {};
  }
};

/** Match Prettier's `quoteProps: as-needed` so generated output passes `format:check`. */
const asKey = (id) => (/^[A-Za-z_$][\w$]*$/.test(id) ? id : `'${id}'`);

const writeManifest = async (entries) => {
  const sorted = Object.keys(entries).sort();
  const lines = sorted.map((id) => `  ${asKey(id)}: '${entries[id]}',`).join('\n');
  const contents = `// AUTO-GENERATED by scripts/generate-project-screenshots.mjs — do not edit by hand.
// Run \`npm run screenshots\` to regenerate.
export const projectScreenshots: Record<string, string> = {
${lines}
};
`;
  await writeFile(manifestPath, contents, 'utf8');
};

const run = async () => {
  await mkdir(outputDir, { recursive: true });

  const projects = onlyId ? projectData.filter((p) => p.id === onlyId) : projectData;
  if (onlyId && projects.length === 0) {
    console.error(`No project found with id "${onlyId}"`);
    process.exit(1);
  }

  const manifest = await readExistingManifest();

  const browser = await puppeteer.launch({ headless: true });
  try {
    for (const project of projects) {
      const url = captureUrl(project);
      const fileName = `${project.id}.png`;
      const filePath = join(outputDir, fileName);
      const page = await browser.newPage();
      try {
        await page.setViewport(VIEWPORT);
        console.log(`→ ${project.id}: ${url}`);
        await page.goto(url, { waitUntil: 'networkidle2', timeout: NAV_TIMEOUT });
        await new Promise((resolve) => setTimeout(resolve, SETTLE_MS));
        await page.screenshot({ path: filePath, type: 'png' });
        manifest[project.id] = `/images/projects/${fileName}`;
        console.log(`  ✓ saved ${fileName}`);
      } catch (error) {
        console.warn(`  ✗ failed ${project.id}: ${error.message}`);
      } finally {
        await page.close();
      }
    }
  } finally {
    await browser.close();
  }

  await writeManifest(manifest);
  console.log(`\nManifest written: ${manifestPath} (${Object.keys(manifest).length} entries)`);
};

run().catch((error) => {
  console.error(error);
  process.exit(1);
});
